#!/usr/bin/env python3
"""
macOS Gestures Manager for Omarchy
Manages configuration and generates Hyprland Lua gesture bindings.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict

CONFIG_DIR = Path.home() / ".config" / "omarchy"
CONFIG_FILE = CONFIG_DIR / "macos-gestures.json"
HYPR_DIR = Path.home() / ".config" / "hypr"
HYPR_GESTURES_FILE = HYPR_DIR / "macos_gestures.lua"
HYPRLAND_MAIN_CONF = HYPR_DIR / "hyprland.lua"

DEFAULT_CONFIG: Dict[str, Any] = {
    "enabled": True,
    "mode": "standard",  # "standard" (3-finger nav) or "drag3fg" (3-finger drag + 4-finger nav)
    "naturalScroll": True,
    "clickfinger": True,
    "workspaceSwipe": True,
    "workspaceSwipeFingers": 3,
    "missionControlFingers": 3,
    "appExposeFingers": 3,
    "launchpadFingers": 4,
    "showDesktopFingers": 4,
    "drag3fg": False,
    "scrollFactor": 0.4,
}


def load_config() -> Dict[str, Any]:
    config = dict(DEFAULT_CONFIG)
    if CONFIG_FILE.exists():
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                saved = json.load(f)
                if isinstance(saved, dict):
                    config.update(saved)
        except Exception as e:
            print(f"[warning] Failed to read {CONFIG_FILE}: {e}", file=sys.stderr)
    return config


def save_config(config: Dict[str, Any]) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        json.dump(config, f, indent=2)


def generate_lua(config: Dict[str, Any]) -> str:
    if not config.get("enabled", True):
        return """-- macOS Gestures for Hyprland / Omarchy (DISABLED)
-- This file is auto-generated by io.github.devmercenario.macos-gestures.
-- Gestures are currently disabled in ~/.config/omarchy/macos-gestures.json
"""

    mode = config.get("mode", "standard")
    is_drag3fg = mode == "drag3fg" or config.get("drag3fg", False)

    # In drag3fg mode, 3 fingers are dedicated to window dragging;
    # navigation swipes are moved to 4 fingers, exactly matching macOS behavior.
    ws_fingers = 4 if is_drag3fg else int(config.get("workspaceSwipeFingers", 3))
    mc_fingers = 4 if is_drag3fg else int(config.get("missionControlFingers", 3))
    expose_fingers = 4 if is_drag3fg else int(config.get("appExposeFingers", 3))

    natural_scroll = "true" if config.get("naturalScroll", True) else "false"
    clickfinger = "true" if config.get("clickfinger", True) else "false"
    drag3fg_val = "1" if is_drag3fg else "0"
    scroll_factor = float(config.get("scrollFactor", 0.4))

    lua_code = f"""-- macOS Gestures for Hyprland / Omarchy
-- Auto-generated by io.github.devmercenario.macos-gestures
-- Mode: {mode} (drag_3fg={drag3fg_val})

hl.config({{
  input = {{
    touchpad = {{
      natural_scroll = {natural_scroll},
      clickfinger_behavior = {clickfinger},
      drag_3fg = {drag3fg_val},
      scroll_factor = {scroll_factor:.2f},
    }},
  }},
}})

-- 1. Spaces / Workspaces Swipe (1:1 continuous tracking)
hl.gesture({{
  fingers = {ws_fingers},
  direction = "horizontal",
  action = "workspace",
}})

-- 2. Mission Control (Window overview across all workspaces)
hl.gesture({{
  fingers = {mc_fingers},
  direction = "up",
  action = function()
    hl.exec_cmd("omarchy-shell shell toggle io.github.devmercenario.macos-gestures")
  end,
}})

-- 3. App Exposé (Windows of the currently focused application)
hl.gesture({{
  fingers = {expose_fingers},
  direction = "down",
  action = function()
    hl.exec_cmd("omarchy-shell io.github.devmercenario.macos-gestures appExpose")
  end,
}})

-- 4 & 5. Launchpad (Pinch In) & Show Desktop (Pinch Out / Spread) with 4 fingers
hl.gesture({{
  fingers = 4,
  direction = "pinch",
  action = {{
    finish = function(e)
      if e and e.delta and e.delta < 0 then
        -- Pinch In -> Launchpad
        hl.exec_cmd("omarchy-shell omarchy.dock apps")
      else
        -- Pinch Out -> Show Desktop
        hl.exec_cmd("omarchy-shell io.github.devmercenario.macos-gestures showDesktop")
      end
    end,
  }},
}})
"""
    return lua_code


def sync_hyprland(config: Dict[str, Any]) -> bool:
    HYPR_DIR.mkdir(parents=True, exist_ok=True)
    content = generate_lua(config)
    with open(HYPR_GESTURES_FILE, "w", encoding="utf-8") as f:
        f.write(content)

    # Ensure hyprland.lua contains the safe require hook
    ensure_hyprland_hook()

    # Reload hyprland
    res = subprocess.run(["hyprctl", "reload"], capture_output=True, text=True)
    return res.returncode == 0


def ensure_hyprland_hook() -> bool:
    hook_line = 'pcall(require, "hypr.macos_gestures")'
    if not HYPRLAND_MAIN_CONF.exists():
        return False

    with open(HYPRLAND_MAIN_CONF, "r", encoding="utf-8") as f:
        content = f.read()

    if hook_line in content:
        return True

    # Append hook safely before end
    new_content = content.rstrip() + f"\n\n-- macOS Gestures Plugin integration\n{hook_line}\n"
    with open(HYPRLAND_MAIN_CONF, "w", encoding="utf-8") as f:
        f.write(new_content)
    return True


def remove_hyprland_hook() -> None:
    hook_line = 'pcall(require, "hypr.macos_gestures")'
    if not HYPRLAND_MAIN_CONF.exists():
        return

    with open(HYPRLAND_MAIN_CONF, "r", encoding="utf-8") as f:
        lines = f.readlines()

    filtered = [l for l in lines if hook_line not in l and "macOS Gestures Plugin integration" not in l]
    with open(HYPRLAND_MAIN_CONF, "w", encoding="utf-8") as f:
        f.writelines(filtered)


def main() -> int:
    parser = argparse.ArgumentParser(description="macOS Gestures Manager for Omarchy")
    subparsers = parser.add_subparsers(dest="command")

    subparsers.add_parser("status", help="Get current status (supports --json)")
    subparsers.add_parser("enable", help="Enable macOS gestures")
    subparsers.add_parser("disable", help="Disable macOS gestures")
    subparsers.add_parser("toggle", help="Toggle enabled/disabled")
    subparsers.add_parser("sync", help="Regenerate Lua config and reload Hyprland")

    mode_parser = subparsers.add_parser("mode", help="Set gesture profile mode")
    mode_parser.add_argument("name", choices=["standard", "drag3fg"], help="standard or drag3fg")

    ns_parser = subparsers.add_parser("natural-scroll", help="Configure natural scrolling")
    ns_parser.add_argument("state", choices=["on", "off", "toggle"], help="on, off or toggle")

    parser.add_argument("--json", action="store_true", help="Output JSON for status")

    args = parser.parse_args()
    config = load_config()

    if args.command == "status" or not args.command:
        if args.json:
            print(json.dumps(config, indent=2))
        else:
            status_str = "ENABLED" if config.get("enabled", True) else "DISABLED"
            mode = config.get("mode", "standard")
            is_drag = mode == "drag3fg" or config.get("drag3fg", False)
            print(f"macOS Gestures: {status_str}")
            print(f"Profile Mode:   {mode}")
            print(f"3-Finger Drag:  {'Enabled' if is_drag else 'Disabled'}")
            print(f"Natural Scroll: {'Enabled' if config.get('naturalScroll', True) else 'Disabled'}")
            print(f"Spaces Swipe:   {'4 fingers' if is_drag else '3 fingers'} (Horizontal)")
            print(f"Mission Control:{'4 fingers' if is_drag else '3 fingers'} (Swipe Up)")
            print(f"App Exposé:     {'4 fingers' if is_drag else '3 fingers'} (Swipe Down)")
            print("Launchpad:      4 fingers (Pinch In)")
            print("Show Desktop:   4 fingers (Pinch Out)")
            print(f"Config File:    {CONFIG_FILE}")
            print(f"Hyprland Lua:   {HYPR_GESTURES_FILE}")
        return 0

    elif args.command == "enable":
        config["enabled"] = True
        save_config(config)
        sync_hyprland(config)
        print("macOS Gestures enabled.")
        return 0

    elif args.command == "disable":
        config["enabled"] = False
        save_config(config)
        sync_hyprland(config)
        print("macOS Gestures disabled.")
        return 0

    elif args.command == "toggle":
        config["enabled"] = not config.get("enabled", True)
        save_config(config)
        sync_hyprland(config)
        print(f"macOS Gestures {'enabled' if config['enabled'] else 'disabled'}.")
        return 0

    elif args.command == "mode":
        mode = args.name
        config["mode"] = mode
        if mode == "drag3fg":
            config["drag3fg"] = True
            config["workspaceSwipeFingers"] = 4
            config["missionControlFingers"] = 4
            config["appExposeFingers"] = 4
        else:
            config["drag3fg"] = False
            config["workspaceSwipeFingers"] = 3
            config["missionControlFingers"] = 3
            config["appExposeFingers"] = 3
        save_config(config)
        sync_hyprland(config)
        print(f"macOS Gestures profile mode set to: {mode}")
        return 0

    elif args.command == "natural-scroll":
        if args.state == "on":
            config["naturalScroll"] = True
        elif args.state == "off":
            config["naturalScroll"] = False
        elif args.state == "toggle":
            config["naturalScroll"] = not config.get("naturalScroll", True)
        save_config(config)
        sync_hyprland(config)
        print(f"Natural scroll {'enabled' if config['naturalScroll'] else 'disabled'}.")
        return 0

    elif args.command == "sync":
        sync_hyprland(config)
        print("macOS Gestures synced with Hyprland.")
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())
